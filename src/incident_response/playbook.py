"""
Incident Response Playbooks & Containment Automation
Automatically generates incident tickets, notifies SOC, adds malicious IPs to blocklist, and crafts firewall rules.
"""
from typing import Dict, Any
from src.db.database import create_incident, add_to_blocklist, log_alert
from src.threat_intel.geoip import get_geoip_info

def execute_incident_response(prediction_result: Dict[str, Any]) -> Dict[str, Any]:
    src_ip = prediction_result.get("src_ip", "192.168.1.150")
    dst_ip = prediction_result.get("dst_ip", "10.0.0.1")
    dst_port = prediction_result.get("dst_port", 80)
    attack_type = prediction_result.get("attack_type", "DoS")
    threat_score = float(prediction_result.get("threat_score", 85.0))
    severity = prediction_result.get("severity", "HIGH")
    confidence = float(prediction_result.get("confidence", 0.95))
    
    # 1. Geo-IP & Threat Intel lookup
    geo_data = get_geoip_info(src_ip)
    
    # 2. Automated Incident Ticket Creation
    incident_payload = {
        "src_ip": src_ip,
        "dst_ip": dst_ip,
        "dst_port": dst_port,
        "attack_type": attack_type,
        "threat_score": threat_score,
        "severity": severity,
        "confidence": confidence,
        "status": "New",
        "assignee": "Tier 1 SOC Analyst",
        "resolution_notes": f"Auto-generated by SentinelNet Playbook. Origin: {geo_data.get('country')} ({geo_data.get('code')}), ASN: {geo_data.get('asn')}"
    }
    ticket_id = create_incident(incident_payload)
    
    # 3. Log alert to security event stream
    log_alert({
        "src_ip": src_ip,
        "dst_ip": dst_ip,
        "dst_port": dst_port,
        "attack_type": attack_type,
        "threat_score": threat_score,
        "severity": severity,
        "confidence": confidence,
        "detection_reason": f"AI Consensus ({attack_type})",
        "raw_flow": prediction_result.get("raw_flow", {})
    })
    
    # 4. Containment & Blocklist (for HIGH or CRITICAL threats)
    actions = [f"Generated incident ticket {ticket_id}", "Queried Geo-IP threat intelligence"]
    if severity in ["HIGH", "CRITICAL"]:
        add_to_blocklist(src_ip, reason=f"Automated containment: {attack_type} [Score: {threat_score}]", severity=severity)
        actions.append(f"Quarantined attacker IP {src_ip} into firewall containment blocklist")
        
    # 5. Generate OS firewall rules
    iptables_rule = f"iptables -A INPUT -s {src_ip} -j DROP"
    windows_firewall_rule = f'netsh advfirewall firewall add rule name="Block_NIDS_{src_ip}" dir=in action=block remoteip={src_ip}'
    
    return {
        "status": "success",
        "ticket_id": ticket_id,
        "actions_taken": actions,
        "contained_ip": src_ip,
        "firewall_rules": {
            "linux_iptables": iptables_rule,
            "windows_netsh": windows_firewall_rule
        },
        "geo_intel": geo_data
    }
